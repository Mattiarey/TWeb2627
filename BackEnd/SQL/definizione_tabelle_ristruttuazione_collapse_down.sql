/* Tables */
CREATE TABLE HOTEL (
    id_hotel INTEGER NOT NULL,
    nome INTEGER NOT NULL,
    indirizzo INTEGER NOT NULL,
    diSTANZE INTEGER NOT NULL,
    telefono INTEGER,
    email INTEGER,
    PRIMARY KEY (id_hotel)
);
CREATE TABLE SOCIETA (
    id_societa INTEGER NOT NULL,
    nome INTEGER NOT NULL,
    regione_provenienza INTEGER,
    nazione_provenienza INTEGER,
    email_referente INTEGER,
    telefono_referente INTEGER,
    PRIMARY KEY (id_societa)
);
CREATE TABLE GIOCATORI (
    id_persona INTEGER NOT NULL,
    data_nascita INTEGER NOT NULL,
    nome INTEGER NOT NULL,
    cognome INTEGER NOT NULL,
    PRIMARY KEY (id_persona)
);
CREATE TABLE STANZE (
    id_STANZE INTEGER NOT NULL,
    numero INTEGER NOT NULL,
    posti_letto INTEGER NOT NULL,
    PRIMARY KEY (id_STANZE)
);
CREATE TABLE GENITORI (
    id_persona INTEGER NOT NULL,
    con_figlio INTEGER NOT NULL,
    grado_parentela INTEGER NOT NULL,
    nome INTEGER NOT NULL,
    cognome INTEGER NOT NULL,
    PRIMARY KEY (id_persona)
);
CREATE TABLE TORNEI (
    id_TORNEI INTEGER NOT NULL,
    nome INTEGER NOT NULL,
    data_inizio INTEGER NOT NULL,
    data_fine INTEGER NOT NULL,
    luogo INTEGER NOT NULL,
    PRIMARY KEY (id_TORNEI)
);
CREATE TABLE CATEGORIE (
    id_CATEGORIE INTEGER NOT NULL,
    formato_gioco INTEGER NOT NULL,
    tipo_CATEGORIE INTEGER NOT NULL,
    PRIMARY KEY (id_CATEGORIE)
);
CREATE TABLE SQUADRE (
    id_SQUADRE INTEGER NOT NULL,
    nome INTEGER NOT NULL,
    SOCIETA_id_societa INTEGER NOT NULL,
    CATEGORIE_id_CATEGORIE INTEGER NOT NULL,
    PRIMARY KEY (id_SQUADRE),
    FOREIGN KEY (SOCIETA_id_societa) REFERENCES SOCIETA (id_societa)
    ON DELETE NO ACTION
    ON UPDATE NO ACTION,
    FOREIGN KEY (CATEGORIE_id_CATEGORIE) REFERENCES CATEGORIE (id_CATEGORIE)
    ON DELETE NO ACTION
    ON UPDATE NO ACTION
);
CREATE TABLE TARIFFE (
    id_TARIFFE INTEGER NOT NULL,
    costo INTEGER NOT NULL,
    descrizione INTEGER NOT NULL,
    TORNEI_id_TORNEI INTEGER NOT NULL,
    PRIMARY KEY (id_TARIFFE),
    FOREIGN KEY (TORNEI_id_TORNEI) REFERENCES TORNEI (id_TORNEI)
    ON DELETE NO ACTION
    ON UPDATE NO ACTION
);
CREATE TABLE ISCRIZIONI (
    id_ISCRIZIONI INTEGER NOT NULL,
    data_ISCRIZIONI INTEGER NOT NULL,
    stato INTEGER NOT NULL,
    note INTEGER,
    TORNEI_id_TORNEI INTEGER NOT NULL,
    SQUADRE_id_SQUADRE INTEGER NOT NULL,
    PRIMARY KEY (id_ISCRIZIONI),
    FOREIGN KEY (TORNEI_id_TORNEI) REFERENCES TORNEI (id_TORNEI)
    ON DELETE NO ACTION
    ON UPDATE NO ACTION,
    FOREIGN KEY (SQUADRE_id_SQUADRE) REFERENCES SQUADRE (id_SQUADRE)
    ON DELETE NO ACTION
    ON UPDATE NO ACTION
);
CREATE TABLE AVERE (
    SQUADRE_id_SQUADRE INTEGER NOT NULL,
    GIOCATORI_id_persona INTEGER NOT NULL,
    PRIMARY KEY (SQUADRE_id_SQUADRE, GIOCATORI_id_persona),
    FOREIGN KEY (SQUADRE_id_SQUADRE) REFERENCES SQUADRE (id_SQUADRE)
    ON DELETE NO ACTION
    ON UPDATE NO ACTION,
    FOREIGN KEY (GIOCATORI_id_persona) REFERENCES GIOCATORI (id_persona)
    ON DELETE NO ACTION
    ON UPDATE NO ACTION
);
CREATE TABLE FORNIRE (
    HOTEL_id_hotel INTEGER NOT NULL,
    STANZE_id_STANZE INTEGER NOT NULL,
    TORNEI_id_TORNEI INTEGER NOT NULL,
    PRIMARY KEY (HOTEL_id_hotel, STANZE_id_STANZE, TORNEI_id_TORNEI),
    FOREIGN KEY (HOTEL_id_hotel) REFERENCES HOTEL (id_hotel)
    ON DELETE NO ACTION
    ON UPDATE NO ACTION,
    FOREIGN KEY (STANZE_id_STANZE) REFERENCES STANZE (id_STANZE)
    ON DELETE NO ACTION
    ON UPDATE NO ACTION,
    FOREIGN KEY (TORNEI_id_TORNEI) REFERENCES TORNEI (id_TORNEI)
    ON DELETE NO ACTION
    ON UPDATE NO ACTION
);
CREATE TABLE SCEGLIERE (
    GIOCATORI_id_persona INTEGER NOT NULL,
    TARIFFE_id_TARIFFE INTEGER NOT NULL,
    PRIMARY KEY (GIOCATORI_id_persona, TARIFFE_id_TARIFFE),
    FOREIGN KEY (GIOCATORI_id_persona) REFERENCES GIOCATORI (id_persona)
    ON DELETE NO ACTION
    ON UPDATE NO ACTION,
    FOREIGN KEY (TARIFFE_id_TARIFFE) REFERENCES TARIFFE (id_TARIFFE)
    ON DELETE NO ACTION
    ON UPDATE NO ACTION
);
CREATE TABLE RISERVARE (
    STANZE_id_STANZE INTEGER NOT NULL,
    ISCRIZIONI_id_ISCRIZIONI INTEGER NOT NULL,
    PRIMARY KEY (STANZE_id_STANZE, ISCRIZIONI_id_ISCRIZIONI),
    FOREIGN KEY (STANZE_id_STANZE) REFERENCES STANZE (id_STANZE)
    ON DELETE NO ACTION
    ON UPDATE NO ACTION,
    FOREIGN KEY (ISCRIZIONI_id_ISCRIZIONI) REFERENCES ISCRIZIONI (id_ISCRIZIONI)
    ON DELETE NO ACTION
    ON UPDATE NO ACTION
);
CREATE TABLE COMPORRE (
    GIOCATORI_id_persona INTEGER NOT NULL,
    ISCRIZIONI_id_ISCRIZIONI INTEGER NOT NULL,
    PRIMARY KEY (GIOCATORI_id_persona, ISCRIZIONI_id_ISCRIZIONI),
    FOREIGN KEY (GIOCATORI_id_persona) REFERENCES GIOCATORI (id_persona)
    ON DELETE NO ACTION
    ON UPDATE NO ACTION,
    FOREIGN KEY (ISCRIZIONI_id_ISCRIZIONI) REFERENCES ISCRIZIONI (id_ISCRIZIONI)
    ON DELETE NO ACTION
    ON UPDATE NO ACTION
);
CREATE TABLE OCCUPARE_GIOCATORI (
    GIOCATORI_id_persona INTEGER NOT NULL,
    STANZE_id_STANZE INTEGER NOT NULL,
    PRIMARY KEY (GIOCATORI_id_persona, STANZE_id_STANZE),
    FOREIGN KEY (GIOCATORI_id_persona) REFERENCES GIOCATORI (id_persona)
    ON DELETE NO ACTION
    ON UPDATE NO ACTION,
    FOREIGN KEY (STANZE_id_STANZE) REFERENCES STANZE (id_STANZE)
    ON DELETE NO ACTION
    ON UPDATE NO ACTION
);
CREATE TABLE OCCUPARE_GENITORI (
    STANZE_id_STANZE INTEGER NOT NULL,
    GENITORI_id_persona INTEGER NOT NULL,
    PRIMARY KEY (STANZE_id_STANZE, GENITORI_id_persona),
    FOREIGN KEY (STANZE_id_STANZE) REFERENCES STANZE (id_STANZE)
    ON DELETE NO ACTION
    ON UPDATE NO ACTION,
    FOREIGN KEY (GENITORI_id_persona) REFERENCES GENITORI (id_persona)
    ON DELETE NO ACTION
    ON UPDATE NO ACTION
);